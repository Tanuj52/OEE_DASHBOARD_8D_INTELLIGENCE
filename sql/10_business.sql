-- ============================================================
-- 10_business.sql
-- Business modules: rolling order book, spare-part stock, corrective actions
-- and the daily digest email.
--
--   PRODUCTION.ORDER_BOOK            open customer orders per machine, kept about four
--                                    weeks ahead by ROLL_ORDER_BOOK (daily task)
--   OPERATIONS.V_PART_STOCK          stock per spare part: opening balance (PARTS_INVENTORY)
--                                    plus the ledger the app writes (PART_TRANSACTIONS)
--   OPERATIONS.V_CAPA_OPEN           open corrective and preventive actions with overdue flag
--   OPERATIONS.BUILD_DAILY_DIGEST    digest email content; SEND_DAILY_DIGEST sends it to the
--                                    recipient lists marked "Daily digest" (daily task)
--
-- Run by `python sql/setup.py --steps business`, which first uploads the handler code
-- (sql/procs.py and the standard-library modules from snowflake_app/core) to
-- OPERATIONS.APP_LIB and fills in EIGHT_D_TZ with the account's time zone.
-- Requires 07_operations.sql. Tasks run on COMPUTE_WH for a few seconds a day.
-- ============================================================

CREATE TABLE IF NOT EXISTS MANUFACTURING_8D.PRODUCTION.ORDER_BOOK (
  ORDER_ID STRING, CUSTOMER_ID STRING, PRODUCT_ID STRING, MACHINE_ID STRING,
  QTY NUMBER, UNIT_PRICE_USD FLOAT, ORDER_VALUE_USD FLOAT,
  START_DATE DATE, DUE_DATE DATE,
  PRIORITY STRING,                   -- Standard | Rush | Critical
  STATUS STRING,                     -- Open | In production | Shipped
  LATE_PENALTY_USD_PER_DAY FLOAT, RELEASED_ON DATE,
  PRIMARY KEY (ORDER_ID))
  COMMENT = '8D Intelligence: rolling order book (ROLL_ORDER_BOOK keeps four weeks of open orders per machine)';

CREATE TABLE IF NOT EXISTS MANUFACTURING_8D.OPERATIONS.CAPA_ACTIONS (
  ACTION_ID STRING, RUN_ID STRING, MACHINE_ID STRING, DISCIPLINE STRING, ACTION STRING,
  OWNER_ID STRING, OWNER_NAME STRING, OWNER_ROLE STRING, STATUS STRING, DUE_AT TIMESTAMP_TZ,
  CREATED_AT TIMESTAMP_TZ, DONE_AT TIMESTAMP_TZ, VERIFIED_AT TIMESTAMP_TZ, RESULT STRING,
  DATA VARIANT, PRIMARY KEY (ACTION_ID));

CREATE TABLE IF NOT EXISTS MANUFACTURING_8D.OPERATIONS.PART_TRANSACTIONS (
  TXN_ID STRING, TS TIMESTAMP_TZ, PART_ID STRING, KIND STRING, QTY NUMBER,
  WO_ID STRING, PO_ID STRING, USER_NAME STRING, NOTE STRING,
  DATA VARIANT, PRIMARY KEY (TXN_ID));

CREATE TABLE IF NOT EXISTS MANUFACTURING_8D.OPERATIONS.PURCHASE_ORDERS (
  PO_ID STRING, PART_ID STRING, PART_NAME STRING, VENDOR_NAME STRING, QTY NUMBER, UNIT_COST_USD FLOAT,
  STATUS STRING, REASON STRING, WO_ID STRING, CREATED_AT TIMESTAMP_TZ, ORDERED_AT TIMESTAMP_TZ,
  EXPECTED_AT TIMESTAMP_TZ, RECEIVED_AT TIMESTAMP_TZ, CREATED_BY STRING,
  DATA VARIANT, PRIMARY KEY (PO_ID));

CREATE OR REPLACE VIEW MANUFACTURING_8D.OPERATIONS.V_PART_STOCK
  COMMENT = 'Spare-part stock: opening balance plus every receipt, issue, adjustment and reservation'
AS
WITH t AS (
  SELECT PART_ID,
         SUM(IFF(KIND = 'receive', QTY, 0)) AS received,
         SUM(IFF(KIND = 'issue', QTY, 0)) AS issued,
         SUM(IFF(KIND = 'adjust', QTY, 0)) AS adjusted,
         SUM(IFF(KIND = 'reserve', QTY, IFF(KIND = 'release', -QTY, 0))) AS held
  FROM MANUFACTURING_8D.OPERATIONS.PART_TRANSACTIONS GROUP BY PART_ID),
po AS (
  SELECT PART_ID, SUM(QTY) AS po_qty
  FROM MANUFACTURING_8D.OPERATIONS.PURCHASE_ORDERS
  WHERE STATUS IN ('requested', 'approved', 'ordered') GROUP BY PART_ID)
SELECT p.PART_ID, p.PART_NAME, p.CATEGORY, p.MACHINE_COMPATIBILITY, p.REORDER_POINT, p.UNIT_COST_USD,
       v.VENDOR_NAME, v.LEAD_TIME_DAYS, v.MIN_ORDER_QTY,
       p.QTY_ON_HAND AS OPENING_QTY,
       p.QTY_ON_HAND + COALESCE(t.received, 0) - COALESCE(t.issued, 0) + COALESCE(t.adjusted, 0) AS ON_HAND,
       GREATEST(COALESCE(t.held, 0), 0) AS RESERVED,
       ON_HAND - RESERVED AS AVAILABLE,
       COALESCE(po.po_qty, 0) AS INCOMING,
       GREATEST(ON_HAND, 0) * p.UNIT_COST_USD AS STOCK_VALUE_USD,
       (AVAILABLE + INCOMING <= p.REORDER_POINT) OR AVAILABLE < 0 AS TO_ORDER
FROM MANUFACTURING_8D.PRODUCTION.PARTS_INVENTORY p
LEFT JOIN MANUFACTURING_8D.PRODUCTION.PART_VENDORS v ON v.PART_ID = p.PART_ID
LEFT JOIN t ON t.PART_ID = p.PART_ID
LEFT JOIN po ON po.PART_ID = p.PART_ID;

CREATE OR REPLACE VIEW MANUFACTURING_8D.OPERATIONS.V_CAPA_OPEN
  COMMENT = 'Open corrective and preventive actions from 8D reports, with owner and overdue flag'
AS
SELECT ACTION_ID, RUN_ID, MACHINE_ID, DISCIPLINE, ACTION, OWNER_ID, OWNER_NAME, OWNER_ROLE, STATUS, DUE_AT,
       DUE_AT < CURRENT_TIMESTAMP() AS OVERDUE,
       ROUND(DATEDIFF('hour', CURRENT_TIMESTAMP(), DUE_AT) / 24, 1) AS DAYS_LEFT
FROM MANUFACTURING_8D.OPERATIONS.CAPA_ACTIONS
WHERE STATUS IN ('open', 'in_progress');

CREATE STAGE IF NOT EXISTS MANUFACTURING_8D.OPERATIONS.APP_LIB
  COMMENT = '8D Intelligence: stored-procedure code (uploaded by sql/setup.py)';

CREATE OR REPLACE PROCEDURE MANUFACTURING_8D.PRODUCTION.ROLL_ORDER_BOOK(DB STRING)
  RETURNS STRING LANGUAGE PYTHON RUNTIME_VERSION = '3.11'
  PACKAGES = ('snowflake-snowpark-python')
  IMPORTS = ('@MANUFACTURING_8D.OPERATIONS.APP_LIB/eight_d_procs.zip')
  HANDLER = 'procs.roll_order_book'
  COMMENT = 'Keep about four weeks of open customer orders on every machine'
  EXECUTE AS OWNER;

CREATE OR REPLACE PROCEDURE MANUFACTURING_8D.OPERATIONS.BUILD_DAILY_DIGEST(DB STRING)
  RETURNS VARIANT LANGUAGE PYTHON RUNTIME_VERSION = '3.11'
  PACKAGES = ('snowflake-snowpark-python')
  IMPORTS = ('@MANUFACTURING_8D.OPERATIONS.APP_LIB/eight_d_procs.zip')
  HANDLER = 'procs.build_daily_digest'
  COMMENT = 'Daily digest email content: overdue actions, parts to order, purchasing, orders at risk'
  EXECUTE AS OWNER;

CREATE OR REPLACE PROCEDURE MANUFACTURING_8D.OPERATIONS.SEND_DAILY_DIGEST(DB STRING, INTEGRATION STRING)
  RETURNS STRING LANGUAGE PYTHON RUNTIME_VERSION = '3.11'
  PACKAGES = ('snowflake-snowpark-python')
  IMPORTS = ('@MANUFACTURING_8D.OPERATIONS.APP_LIB/eight_d_procs.zip')
  HANDLER = 'procs.send_daily_digest'
  COMMENT = 'Send the daily digest to the recipient lists marked Daily digest'
  EXECUTE AS OWNER;

CALL MANUFACTURING_8D.PRODUCTION.ROLL_ORDER_BOOK('MANUFACTURING_8D');

CREATE OR REPLACE TASK MANUFACTURING_8D.PRODUCTION.EIGHT_D_ROLL_ORDER_BOOK
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = 'USING CRON 15 0 * * * EIGHT_D_TZ'
  COMMENT = '8D Intelligence: roll the order book forward every night'
AS CALL MANUFACTURING_8D.PRODUCTION.ROLL_ORDER_BOOK('MANUFACTURING_8D');

CREATE OR REPLACE TASK MANUFACTURING_8D.OPERATIONS.EIGHT_D_DAILY_DIGEST
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = 'USING CRON 0 7 * * * EIGHT_D_TZ'
  COMMENT = '8D Intelligence: daily digest email (hour set in the app, Settings > Email)'
AS CALL MANUFACTURING_8D.OPERATIONS.SEND_DAILY_DIGEST('MANUFACTURING_8D', 'EIGHT_D_REPORT_EMAIL');

ALTER TASK MANUFACTURING_8D.PRODUCTION.EIGHT_D_ROLL_ORDER_BOOK RESUME;
ALTER TASK MANUFACTURING_8D.OPERATIONS.EIGHT_D_DAILY_DIGEST RESUME;

